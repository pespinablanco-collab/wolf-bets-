-- ------------------------------------------------------------
-- 6) Crear / actualizar SUPERCUOTA
--
-- Al activarla:
--   markets.odd pasa a ser la supercuota.
--   original_odd conserva la cuota anterior.
--
-- Al desactivarla:
--   markets.odd vuelve a original_odd.
-- ------------------------------------------------------------
create or replace function public.admin_set_supercuota(
    p_market_id bigint,
    p_super_odd numeric,
    p_label text default 'SUPERCUOTA',
    p_image_url text default null,
    p_banner_url text default null,
    p_expires_at timestamptz default null,
    p_sort_order integer default 0
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
    market_odd numeric;
    super_id bigint;
begin

    if not public.is_admin() then
        raise exception 'No autorizado';
    end if;

    if p_super_odd is null or p_super_odd <= 1 then
        raise exception 'La supercuota debe ser mayor que 1';
    end if;

    select odd
    into market_odd
    from public.markets
    where id = p_market_id
    for update;

    if not found then
        raise exception 'Mercado no encontrado';
    end if;

    -- Si ya existe una supercuota, mantenemos su original_odd.
    insert into public.supercuotas(
        market_id,
        original_odd,
        super_odd,
        label,
        image_url,
        banner_url,
        active,
        expires_at,
        sort_order
    )
    values(
        p_market_id,
        market_odd,
        p_super_odd,
        coalesce(nullif(trim(p_label),''),'SUPERCUOTA'),
        p_image_url,
        p_banner_url,
        true,
        p_expires_at,
        coalesce(p_sort_order,0)
    )
    on conflict(market_id)
    do update set
        super_odd = excluded.super_odd,
        label = excluded.label,
        image_url = excluded.image_url,
        banner_url = excluded.banner_url,
        active = true,
        expires_at = excluded.expires_at,
        sort_order = excluded.sort_order;

    -- Si la fila ya existía y estaba activa, su original_odd
    -- se conserva gracias al ON CONFLICT.
    update public.markets
    set
        odd = p_super_odd,
        is_open = true
    where id = p_market_id;

    select id
    into super_id
    from public.supercuotas
    where market_id = p_market_id;

    return super_id;
end;
$$;

grant execute
on function public.admin_set_supercuota(bigint,numeric,text,text,text,timestamptz,integer)
to authenticated;


-- ------------------------------------------------------------
-- 7) Activar/desactivar SUPERCUOTA
-- ------------------------------------------------------------
create or replace function public.admin_toggle_supercuota(
    p_market_id bigint,
    p_active boolean
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
    original numeric;
begin

    if not public.is_admin() then
        raise exception 'No autorizado';
    end if;

    select original_odd
    into original
    from public.supercuotas
    where market_id = p_market_id
    for update;

    if not found then
        raise exception 'Este mercado no tiene supercuota';
    end if;

    if p_active then
        update public.supercuotas
        set active = true
        where market_id = p_market_id;

        update public.markets m
        set odd = (
            select s.super_odd
            from public.supercuotas s
            where s.market_id = m.id
        ),
        is_open = true
        where m.id = p_market_id;

    else
        update public.markets
        set odd = original
        where id = p_market_id;

        update public.supercuotas
        set active = false
        where market_id = p_market_id;
    end if;

end;
$$;

grant execute
on function public.admin_toggle_supercuota(bigint,boolean)
to authenticated;


-- ------------------------------------------------------------
-- 8) Limpiar supercuotas expiradas
--    No lo ejecutamos automáticamente en cada apuesta; el frontend
--    puede refrescar y el admin también puede desactivarlas.
-- ------------------------------------------------------------
create or replace function public.expire_supercuotas()
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
    n integer;
begin

    update public.markets m
    set odd = s.original_odd
    from public.supercuotas s
    where s.market_id = m.id
      and s.active = true
      and s.expires_at is not null
      and s.expires_at <= now();

    update public.supercuotas
    set active = false
    where active = true
      and expires_at is not null
      and expires_at <= now();

    get diagnostics n = row_count;
    return n;
end;
$$;

grant execute
on function public.expire_supercuotas()
to authenticated;


