-- ------------------------------------------------------------
-- 10) Marcar una selección concreta como NO PASADA
--     No resuelve las otras selecciones pendientes del mismo mercado.
--     Sí marca como perdida la selección en simples/combinadas.
-- ------------------------------------------------------------
create or replace function public.admin_mark_selection_lost(
    p_market_id bigint,
    p_selection text
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
    b record;
    cb record;
begin
    if not public.is_admin() then
        raise exception 'No autorizado';
    end if;

    if trim(coalesce(p_selection,'')) = '' then
        raise exception 'Selección vacía';
    end if;

    for b in
        select * from public.bets
        where market_id = p_market_id
          and status = 'pending'
          and lower(trim(selection)) = lower(trim(p_selection))
    loop
        update public.bets
        set status = 'lost'
        where id = b.id;
    end loop;

    update public.combo_bet_legs
    set status = 'lost'
    where market_id = p_market_id
      and status = 'pending'
      and lower(trim(selection)) = lower(trim(p_selection));

    -- Toda combinada que ya tenga una pata perdida queda perdida.
    for cb in
        select distinct combo_bet_id
        from public.combo_bet_legs
        where market_id = p_market_id
    loop
        if exists(
            select 1 from public.combo_bet_legs
            where combo_bet_id = cb.combo_bet_id
              and status = 'lost'
        ) then
            update public.combo_bets
            set status = 'lost'
            where id = cb.combo_bet_id
              and status = 'pending';
        end if;
    end loop;
end;
$$;

grant execute
on function public.admin_mark_selection_lost(bigint,text)
to authenticated;

