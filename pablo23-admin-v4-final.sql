-- ------------------------------------------------------------
-- 2) Tabla de SUPERCUOTAS
-- La cuota real que se usa para apostar sigue siendo markets.odd.
-- original_odd guarda la cuota anterior para poder restaurarla.
-- ------------------------------------------------------------
create table if not exists public.supercuotas(
    id bigint generated by default as identity primary key,
    market_id bigint not null unique
        references public.markets(id)
        on delete cascade,

    original_odd numeric(8,2) not null
        check(original_odd > 1),

    super_odd numeric(8,2) not null
        check(super_odd > 1),

    label text not null default 'SUPERCUOTA',
    image_url text,
    banner_url text,

    active boolean not null default true,
    expires_at timestamptz,
    sort_order integer not null default 0,

    created_at timestamptz not null default now()
);

alter table public.supercuotas enable row level security;

drop policy if exists "supercuotas readable"
on public.supercuotas;

drop policy if exists "admin manages supercuotas"
on public.supercuotas;

create policy "supercuotas readable"
on public.supercuotas
for select
to authenticated
using(
    active = true
    or public.is_admin()
);

create policy "admin manages supercuotas"
on public.supercuotas
for all
to authenticated
using(public.is_admin())
with check(public.is_admin());


-- ------------------------------------------------------------
-- 3) Actualizar resultado/marcador desde la web
-- ------------------------------------------------------------
create or replace function public.admin_update_match_result(
    p_match_id bigint,
    p_score_home integer default null,
    p_score_away integer default null,
    p_result text default null,
    p_status text default 'finished'
)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin

    if not public.is_admin() then
        raise exception 'No autorizado';
    end if;

    if p_score_home is not null and p_score_home < 0 then
        raise exception 'El marcador local no puede ser negativo';
    end if;

    if p_score_away is not null and p_score_away < 0 then
        raise exception 'El marcador visitante no puede ser negativo';
    end if;

    if p_result is not null
       and p_result not in ('home','draw','away') then
        raise exception 'Resultado inválido';
    end if;

    update public.matches
    set
        score_home = p_score_home,
        score_away = p_score_away,
        result = p_result,
        status = coalesce(nullif(trim(p_status), ''), status)
    where id = p_match_id;

    if not found then
        raise exception 'Partido no encontrado';
    end if;

end;
$$;

grant execute
on function public.admin_update_match_result(bigint,integer,integer,text,text)
to authenticated;


-- ------------------------------------------------------------
-- 4) Borrar partido de forma SEGURA
--
-- Si existen apuestas o selecciones de combinadas, NO permite
-- borrar físicamente el partido para no destruir historial.
-- En ese caso se debe cerrar/cancelar.
-- ------------------------------------------------------------
create or replace function public.admin_delete_match(
    p_match_id bigint
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
    bet_count integer;
    combo_count integer;
begin

    if not public.is_admin() then
        raise exception 'No autorizado';
    end if;

    select count(*)
    into bet_count
    from public.bets b
    where b.match_id = p_match_id;

    select count(*)
    into combo_count
    from public.combo_bet_legs cbl
    join public.markets m
      on m.id = cbl.market_id
    where m.match_id = p_match_id;

    if bet_count > 0 or combo_count > 0 then
        raise exception
            'No se puede borrar este partido porque ya tiene apuestas o combinadas. Ciérralo/cancélalo para conservar el historial.';
    end if;

    delete from public.matches
    where id = p_match_id;

    if not found then
        raise exception 'Partido no encontrado';
    end if;

end;
$$;

grant execute
on function public.admin_delete_match(bigint)
to authenticated;


